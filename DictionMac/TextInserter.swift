import AppKit
import Carbon.HIToolbox
import DictationCore

/// Puts text into whatever app has keyboard focus, the same way Wispr Flow
/// and Handy do: briefly place it on the clipboard, press ⌘V, then put the
/// user's previous clipboard back.
@MainActor
final class TextInserter {
    /// Markers (nspasteboard.org convention) so clipboard managers skip our temporary entry.
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// How long the target app gets to read the clipboard before we restore it.
    var restoreDelay: TimeInterval = 0.6

    /// Tags our own synthetic ⌘V so the hotkey monitor can ignore it.
    nonisolated static let syntheticEventTag: Int64 = 0x44494354  // "DICT"

    /// What we last pasted, and where. Used as the "text before the cursor" when an
    /// app won't expose its text, so back-to-back dictations still get spaced.
    private struct LastInsertion {
        let pid: pid_t
        let element: AXUIElement?
        let text: String
        let date: Date
    }
    private var lastInsertion: LastInsertion?
    private static let memoryLifetime: TimeInterval = 5 * 60

    /// Forget the last insertion: the user typed, clicked, or moved on.
    func forgetLastInsertion() {
        lastInsertion = nil
    }

    func remembered(for snapshot: FocusedTextReader.Snapshot) -> InsertionContext? {
        guard let last = lastInsertion, let pid = snapshot.pid, last.pid == pid,
              Date().timeIntervalSince(last.date) < Self.memoryLifetime else { return nil }
        if let a = last.element, let b = snapshot.element, !CFEqual(a, b) { return nil }
        return InsertionContext(textBefore: last.text, textAfter: nil)
    }

    func insert(_ text: String, into snapshot: FocusedTextReader.Snapshot) {
        insert(text)
        if let pid = snapshot.pid {
            lastInsertion = LastInsertion(pid: pid, element: snapshot.element, text: text, date: Date())
        }
    }

    func insert(_ text: String) {
        let pasteboard = NSPasteboard.general
        let saved = Self.snapshot(pasteboard)

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: Self.transientType)
        pasteboard.setData(Data(), forType: Self.autoGeneratedType)
        let ourChangeCount = pasteboard.changeCount

        Self.pressCommandV()

        DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
            // If something else was copied in the meantime, leave it alone.
            guard pasteboard.changeCount == ourChangeCount else { return }
            Self.restore(saved, to: pasteboard)
        }
    }

    func copyToClipboard(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    private static func pressCommandV() {
        let source = CGEventSource(stateID: .hidSystemState)
        let keyV = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.setIntegerValueField(.eventSourceUserData, value: syntheticEventTag)
        up?.setIntegerValueField(.eventSourceUserData, value: syntheticEventTag)
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private static func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { (type, $0) }
            }
        }
    }

    private static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        let items = snapshot.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }
}
